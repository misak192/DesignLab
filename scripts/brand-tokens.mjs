/**
 * File: scripts/brand-tokens.mjs
 * Description: Generates everything derived from src/lib/brand/tokens.json (the single source of truth):
 *   src/lib/brand/tokens.css        CSS variables (--fw-pink ...) and the Tailwind theme (text-fw-pink ...)
 *   src/lib/brand/Color.kt          Compose colours and the app gradients
 *   src/lib/brand/kotlin.generated.ts  the same Kotlin as a string, for the Copy/Download buttons on /brand
 * Run: npm run brand:tokens
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'brand');
const tokens = JSON.parse(readFileSync(join(dir, 'tokens.json'), 'utf8'));
const all = [...tokens.colours, ...tokens.neutrals];
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const kn = (id) => all.find((c) => c.id === id)?.kt ?? pascal(id);
const argb = (hex) => `0xFF${hex.slice(1).toUpperCase()}`;

const css = `/* GENERATED by scripts/brand-tokens.mjs from tokens.json. Do not edit by hand. */
:root {
${all.map((c) => `  --fw-${c.id}: ${c.hex};`).join('\n')}
}

@theme inline {
${all.map((c) => `  --color-fw-${c.id}: var(--fw-${c.id});`).join('\n')}
}
`;

const spectrum = tokens.colours.map((c) => `FwColors.${kn(c.id)}`).join(', ');
const kt = `// GENERATED by scripts/brand-tokens.mjs from tokens.json (FrissonWorks Design Lab, /brand). Do not edit by hand.
package com.frissonworks.brand

import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color

/** The FrissonWorks core brand colours. Themes may reference these; they never change per theme. */
object FwColors {
${all.map((c) => `    /** ${c.name}: ${c.role} */\n    val ${kn(c.id)} = Color(${argb(c.hex)})`).join('\n')}

    /** Pink to aqua, in order: the full spectrum. */
    val Spectrum: List<Color> = listOf(${spectrum})
}

/** Default gradient pair of every app (from, to). The parent is the full spectrum. */
object FwAppGradients {
${tokens.apps
  .map((a) => (a.spectrum ? `    val ${a.kotlin}: List<Color> = FwColors.Spectrum` : `    val ${a.kotlin}: List<Color> = listOf(FwColors.${kn(a.from)}, FwColors.${kn(a.to)})`))
  .join('\n')}

    fun brush(colours: List<Color>): Brush = Brush.linearGradient(colours)
}
`;

const ts = `// GENERATED by scripts/brand-tokens.mjs. Do not edit by hand.\nexport const KOTLIN_SOURCE = ${JSON.stringify(kt)};\nexport const CSS_SOURCE = ${JSON.stringify(css)};\n`;

writeFileSync(join(dir, 'tokens.css'), css);
writeFileSync(join(dir, 'Color.kt'), kt);
writeFileSync(join(dir, 'kotlin.generated.ts'), ts);
console.log('brand tokens written:', all.length, 'colours,', tokens.apps.length, 'app gradients');
